s = input()
slv = {}
for i in range(len(s)-1):
    if s[i] != ' ' and s[i+1] != ' ':
        ab = s[i] + s[i+1]
        if ab in slv:   # лексема найдена?
            slv[ab] = slv[ab] + 1
        else:
            slv[ab] = 1
# поиск в словаре наиболее встречающейся лексемы 
lxm = ab
mx = slv[ab]
slv1 = dict(sorted(slv.items()))
for k, j in slv1.items():
    if j >= mx:
        lxm = k
        mx = j
print (lxm)
