# 439. Пара букв
# 
# Имеется текст, состоящий из заглавных латинских символов и пробелов, длиной 
# не более 255 символов. Словом в тексте называется последовательность букв, 
# ограниченная пробелами, началом или концом строки. Пара соседних слов 
# разделена хотя бы одним пробелом.
# 
# Найдите такую пару латинских символов, которая чаще всего встречается в тексте
# в качестве подстроки. Например, «LL» является подстрокой в тексте «HELLO», 
# а «HO» — нет.
# 
# Гарантируется, что в тексте есть хотя бы одно слово из 2 и более букв.
# 
# Формат ввода
# В единственной строке задан текст, удовлетворяющий указанным условиям. Длина 
# текста не превосходит 255 символов.
# 
# Формат вывода
# Выведите самую часто встречающуюся пару символов. Если таких сочетаний 
# несколько, то ответом считается лексикографически большее (иначе говоря, 
# то, которое в словаре будет стоять позже).
# 
# https://coderun.yandex.ru/problem/couple-of-letters/description
